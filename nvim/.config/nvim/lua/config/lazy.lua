--------------------------------------------------------------------------------
-- Neovim PDE
--------------------------------------------------------------------------------
-- File: lua/config/lazy.lua
--
-- Purpose:
--   Bootstraps Lazy.nvim and loads every plugin specification.
--
-- Responsibilities:
--   • Install Lazy.nvim if missing.
--   • Prepend Lazy.nvim to the runtime path.
--   • Configure the plugin manager.
--   • Import plugin specifications.
--
-- Notes:
--   This file should remain generic. Plugin configuration belongs inside
--   lua/plugins/.
--------------------------------------------------------------------------------

--------------------------------------------------------------------------------
-- Constants
--------------------------------------------------------------------------------

local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"

--------------------------------------------------------------------------------
-- Bootstrap Lazy.nvim
--------------------------------------------------------------------------------

if not vim.uv.fs_stat(lazypath) then
    vim.fn.system({
        "git",
        "clone",
        "--filter=blob:none",
        "https://github.com/folke/lazy.nvim.git",
        "--branch=stable",
        lazypath,
    })
end

--------------------------------------------------------------------------------
-- Runtime Path
--------------------------------------------------------------------------------

vim.opt.rtp:prepend(lazypath)

--------------------------------------------------------------------------------
-- Setup
--------------------------------------------------------------------------------

require("lazy").setup({
--------------------------------------------------------------------------------
-- Plugin Specifications
--------------------------------------------------------------------------------

spec = {

    --------------------------------------------------------------------------
    -- User Interface
    --------------------------------------------------------------------------

    { import = "plugins.ui" },

    --------------------------------------------------------------------------
    -- Editing
    --------------------------------------------------------------------------

    { import = "plugins.editor" },

    --------------------------------------------------------------------------
    -- Completion
    --------------------------------------------------------------------------

    { import = "plugins.completion" },

    --------------------------------------------------------------------------
    -- Language Server Protocol
    --------------------------------------------------------------------------

    { import = "plugins.lsp" },

    --------------------------------------------------------------------------
    -- Git
    --------------------------------------------------------------------------

    { import = "plugins.git" },

    --------------------------------------------------------------------------
    -- Debugging
    --------------------------------------------------------------------------

    { import = "plugins.debugging" },

    --------------------------------------------------------------------------
    -- Languages
    --------------------------------------------------------------------------

    { import = "plugins.languages" },

},

    --------------------------------------------------------------------------------
    -- Installation
    --------------------------------------------------------------------------------

    install = {

        colorscheme = {
            "catppuccin",
            "habamax",
        },

    },

    --------------------------------------------------------------------------------
    -- Checker
    --------------------------------------------------------------------------------

    checker = {
        enabled = true,
        notify = false,
    },

    --------------------------------------------------------------------------------
    -- Change Detection
    --------------------------------------------------------------------------------

    change_detection = {
        notify = false,
    },

    --------------------------------------------------------------------------------
    -- Performance
    --------------------------------------------------------------------------------

    performance = {

        cache = {
            enabled = true,
        },

        rtp = {

            disabled_plugins = {

                "gzip",
                "matchit",
                "matchparen",
                "netrwPlugin",
                "tarPlugin",
                "tohtml",
                "tutor",
                "zipPlugin",

            },

        },

    },

})
